import { Marked } from 'marked'

export function escapeXml(value) {
  if (value === undefined || value === null) return ''
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

export function cdata(value) {
  return `<![CDATA[${String(value ?? '').replace(/]]>/g, ']]]]><![CDATA[>')}]]>`
}

export function unixSecondsToRfc822(value) {
  if (value === undefined || value === null || value === '') return ''
  const seconds = typeof value === 'number' ? value : Number(value)
  if (!Number.isFinite(seconds)) return ''
  return new Date(seconds * 1000).toUTCString()
}

export function textDateToRfc822(value) {
  if (!value) return ''
  const normalized = String(value).trim().replace(' ', 'T')
  const withZone = /(?:Z|[+-]\d{2}:?\d{2})$/.test(normalized) ? normalized : `${normalized}Z`
  const date = new Date(withZone)
  return Number.isNaN(date.getTime()) ? '' : date.toUTCString()
}

export function resolveUrl(href, siteUrl) {
  const raw = String(href || '').trim()
  if (!raw) return ''
  if (/^[a-z][a-z0-9+.-]*:/i.test(raw) || raw.startsWith('//') || raw.startsWith('#')) return raw
  return `${String(siteUrl).replace(/\/+$/, '')}/${raw.replace(/^\/+/, '')}`
}

export function safeUrl(href, siteUrl) {
  const resolved = resolveUrl(href, siteUrl)
  return /^https?:\/\//i.test(resolved) ? resolved : ''
}

function attr(value) {
  return escapeXml(value)
}

export function renderMarkdown(md, siteUrl) {
  if (!md) return ''
  const marked = new Marked({
    gfm: true,
    breaks: false,
    renderer: {
      html({ text }) {
        return escapeXml(text)
      },
      link({ href, title, tokens }) {
        const text = this.parser.parseInline(tokens)
        const safe = safeUrl(href, siteUrl)
        if (!safe) return text
        return `<a href="${attr(safe)}"${title ? ` title="${attr(title)}"` : ''}>${text}</a>`
      },
      image({ href, title, text, tokens }) {
        const safe = safeUrl(href, siteUrl)
        if (!safe) return escapeXml(text)
        return `<img src="${attr(safe)}" alt="${attr(text)}"${title ? ` title="${attr(title)}"` : ''} />`
      },
    },
  })
  return marked.parse(String(md))
}

function renderItem(item) {
  const lines = ['    <item>']
  if (item.title) lines.push(`      <title>${escapeXml(item.title)}</title>`)
  if (item.link) lines.push(`      <link>${escapeXml(item.link)}</link>`)
  if (item.guid) lines.push(`      <guid isPermaLink="true">${escapeXml(item.guid)}</guid>`)
  if (item.pubDate) lines.push(`      <pubDate>${escapeXml(item.pubDate)}</pubDate>`)
  if (item.description) lines.push(`      <description>${cdata(item.description)}</description>`)
  if (item.content) lines.push(`      <content:encoded>${cdata(item.content)}</content:encoded>`)
  for (const category of item.categories || []) {
    lines.push(`      <category>${escapeXml(category)}</category>`)
  }
  lines.push('    </item>')
  return lines.join('\n')
}

export function buildRss2({ title, link, description, selfUrl, items = [], lastBuildDate }) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/build-rss.mjs — do not edit by hand -->',
    '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">',
    '  <channel>',
    `    <title>${escapeXml(title)}</title>`,
    `    <link>${escapeXml(link)}</link>`,
    `    <description>${escapeXml(description)}</description>`,
    '    <language>en</language>',
    `    <atom:link href="${escapeXml(selfUrl)}" rel="self" type="application/rss+xml" />`,
    lastBuildDate ? `    <lastBuildDate>${escapeXml(lastBuildDate)}</lastBuildDate>` : '',
    ...items.map(renderItem),
    '  </channel>',
    '</rss>',
    '',
  ]
  return lines.filter(line => line !== '').join('\n')
}
