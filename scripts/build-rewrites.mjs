#!/usr/bin/env node
/**
 * 校验 docs/rewritten/batch-*.jsonl 的改写稿并生成 schema/seed-rewrites.sql。
 * 只更新 rw_* 列，不触碰原始字段与其他列；任意一行非法则整批拒绝、不写 seed。
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadRewriteSchema, validateRewriteRow, normalizeRewriteRow } from './lib/rewrite-schema.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = resolve(ROOT, 'docs/rewritten')
const schema = loadRewriteSchema()

function sqlVal(v) {
  if (v == null) return 'NULL'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

const files = readdirSync(DIR).filter(f => /^batch-\d+\.jsonl$/.test(f)).sort()
const rows = []
let errors = 0
for (const file of files) {
  const lines = readFileSync(resolve(DIR, file), 'utf8').split('\n').filter(l => l.trim())
  for (const [i, line] of lines.entries()) {
    let row
    try { row = JSON.parse(line) } catch {
      console.error(`${file}:${i + 1} JSON parse error`); errors++; continue
    }
    const errs = validateRewriteRow(row, schema)
    if (errs.length) {
      console.error(`${file}:${i + 1} ${row.slug}: ${errs.join('; ')}`); errors++; continue
    }
    rows.push(normalizeRewriteRow(row, schema))
  }
}
if (errors) { console.error(`[fail] ${errors} invalid rows; no seed written`); process.exit(1) }

const cols = ['slug', ...schema.fields]
const lines = ['-- Generated by scripts/build-rewrites.mjs — do not edit by hand', '']
for (const row of rows) {
  const values = cols.map(c => {
    const v = row[c] ?? (schema.arrayLimits[c] ? '[]' : null)
    return sqlVal(v)
  })
  // 改写稿只更新已存在的站点，不能 INSERT（name 等列为 NOT NULL）。
  // 只写 rw_* 列，不触碰原始字段与其他列。
  const rwValues = schema.fields.map((f, i) => `${f}=${values[i + 1]}`).join(', ')
  lines.push(`UPDATE submission_sites SET ${rwValues} WHERE slug=${values[0]};`)
}
writeFileSync(resolve(ROOT, 'schema/seed-rewrites.sql'), lines.join('\n') + '\n', 'utf8')
console.log(`[ok] ${rows.length} rewrite rows across ${files.length} batches → seed-rewrites.sql`)
