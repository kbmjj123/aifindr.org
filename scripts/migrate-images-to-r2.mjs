#!/usr/bin/env node
/**
 * 把 submission-sites 的图标 / 截图 / OG 图从 submitmap.com 转存到本站 R2。
 * 逐站下载 → 上传 → 记录状态，失败按指数退避重试 5 次，仍失败保留原 URL 不阻塞。
 * 生成 schema/seed-images.sql（只更新 r2_* 列，幂等可重复执行）。
 *
 * 用法：
 *   node scripts/migrate-images-to-r2.mjs            # 全量
 *   node scripts/migrate-images-to-r2.mjs --limit=3  # 只处理前 3 站（dry-run 验证）
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { S3Client, PutObjectCommand } from '@aws-sdk/client-s3'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// 从 .env 读取 R2 凭证（不依赖 shell 环境）
function loadEnv() {
  const out = {}
  try {
    for (const line of readFileSync(resolve(ROOT, '.env'), 'utf8').split('\n')) {
      const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim())
      if (m) out[m[1]] = m[2]
    }
  } catch { /* .env 可选 */ }
  for (const k of ['R2_ACCOUNT_ID', 'R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY', 'R2_BUCKET_NAME', 'R2_PUBLIC_URL']) {
    if (process.env[k]) out[k] = process.env[k]
  }
  return out
}
const ENV = loadEnv()
const ENDPOINT = ENV.R2_ENDPOINT || `https://${ENV.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`
const PUBLIC_BASE = (ENV.R2_PUBLIC_URL || 'https://cdn.aifindr.org').replace(/\/+$/, '')

const s3 = new S3Client({
  region: 'auto',
  endpoint: ENDPOINT,
  credentials: {
    accessKeyId: ENV.R2_ACCESS_KEY_ID,
    secretAccessKey: ENV.R2_SECRET_ACCESS_KEY,
  },
})

const STATE = resolve(ROOT, 'docs/rewritten/_image-uploads.jsonl')
const SEED = resolve(ROOT, 'schema/seed-images.sql')
const MAX_RETRY = 5
const DELAYS = [1000, 4000, 16000, 64000, 256000]

const KINDS = [
  ['icon', 'icon_url', 'png'],
  ['shot', 'screenshot_url', 'webp'],
  ['og', 'og_image_url', 'png'],
]
// kind → D1 列名（og 的列名是 r2_og_image_url，不是 r2_og_url）
const R2_COL_OF = { icon: 'r2_icon_url', shot: 'r2_screenshot_url', og: 'r2_og_image_url' }

function loadState() {
  if (!existsSync(STATE)) return new Map()
  return new Map(
    readFileSync(STATE, 'utf8').split('\n').filter(l => l.trim())
      .map(line => { const r = JSON.parse(line); return [`${r.slug}:${r.kind}`, r] }),
  )
}
function saveState(state) {
  writeFileSync(STATE, [...state.values()].map(r => JSON.stringify(r)).join('\n') + '\n', 'utf8')
}
const sleep = ms => new Promise(r => setTimeout(r, ms))

async function fetchImage(url) {
  const res = await fetch(url, { headers: { 'User-Agent': 'aifindr-bot/1.0' } })
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  const contentType = res.headers.get('content-type') || ''
  if (!/^image\//.test(contentType)) throw new Error(`not an image: ${contentType}`)
  return { buffer: Buffer.from(await res.arrayBuffer()), contentType }
}

async function uploadOne(site, kind, url, defaultExt, state) {
  const key = `${site.slug}:${kind}`
  const rec = state.get(key) || { slug: site.slug, kind, url, retries: 0, status: 'pending', r2Url: null }
  if (rec.status === 'done' || rec.retries >= MAX_RETRY) return
  rec.url = url
  rec.status = 'uploading'
  state.set(key, rec); saveState(state)
  const r2Key = `submission-sites/${site.slug}/${kind}.${defaultExt}`
  while (rec.retries < MAX_RETRY) {
    try {
      const { buffer, contentType } = await fetchImage(url)
      await s3.send(new PutObjectCommand({
        Bucket: ENV.R2_BUCKET_NAME, Key: r2Key, Body: buffer, ContentType: contentType,
      }))
      rec.status = 'done'
      rec.r2Url = `${PUBLIC_BASE}/${r2Key}`
      delete rec.lastError
      state.set(key, rec); saveState(state)
      console.log(`[ok] ${key}`)
      return
    } catch (e) {
      rec.retries++
      rec.lastError = String(e?.message || e)
      rec.status = rec.retries >= MAX_RETRY ? 'failed' : 'retrying'
      state.set(key, rec); saveState(state)
      if (rec.retries < MAX_RETRY) await sleep(DELAYS[rec.retries - 1])
    }
  }
  console.error(`[fail] ${key} after ${MAX_RETRY} attempts: ${rec.lastError}`)
}

const limitArg = process.argv.find(a => a.startsWith('--limit='))
const LIMIT = limitArg ? parseInt(limitArg.slice('--limit='.length), 10) : Infinity

const data = JSON.parse(readFileSync(resolve(ROOT, 'reports/submission-sites-snapshot.json'), 'utf8'))
const state = loadState()
let processed = 0
for (const site of data.sites) {
  if (processed >= LIMIT) break
  let touched = false
  for (const [kind, srcCol, ext] of KINDS) {
    const url = site[srcCol]
    if (url && /^https:\/\//.test(url)) { await uploadOne(site, kind, url, ext, state); touched = true }
  }
  if (touched) processed++
}

// 只把 done 的项写入 seed（幂等 UPSERT 式 UPDATE，只更新 r2_* 列）
const lines = ['-- Generated by scripts/migrate-images-to-r2.mjs — do not edit by hand', '']
for (const rec of state.values()) {
  if (rec.status !== 'done' || !rec.r2Url) continue
  const col = R2_COL_OF[rec.kind]
  if (!col) continue
  lines.push(`UPDATE submission_sites SET ${col}='${rec.r2Url}' WHERE slug='${rec.slug}';`)
}
writeFileSync(SEED, lines.join('\n') + '\n', 'utf8')
const vals = [...state.values()]
const done = vals.filter(r => r.status === 'done').length
const failed = vals.filter(r => r.status === 'failed').length
console.log(`[ok] ${done} images uploaded, ${failed} failed → seed-images.sql`)
